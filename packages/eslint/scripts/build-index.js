#!/usr/bin/env node
/**
 * build-index.js: writes rules/index.js from the files in rules/.
 *
 * Every `rules/<name>.js` becomes the lint rule `justified/<name>`, so a new
 * rule is a new file and nothing else is edited by hand. Run
 * `npm run index --workspace packages/eslint` after adding or renaming a
 * rule; the tests fail while the index is out of date. If two branches both
 * changed the index, take either side and run this again.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../rules/", import.meta.url));

/** The rule names, from the file names, in order. */
export const ruleFiles = () =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".js") && f !== "index.js")
    .map((f) => f.slice(0, -3))
    .sort();

const camel = (name) => name.replace(/-([a-z0-9])/g, (_m, c) => c.toUpperCase());

/** The text rules/index.js should hold. */
export function renderIndex() {
  const names = ruleFiles();
  return `// Generated by scripts/build-index.js from the files in this folder. Do not edit by hand:
// run \`npm run index --workspace packages/eslint\`.
${names.map((n) => `import ${camel(n)} from "./${n}.js";`).join("\n")}

/** @type {Record<string, import("eslint").Rule.RuleModule>} */
export default {
${names.map((n) => `  "${n}": ${camel(n)},`).join("\n")}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(dir, "index.js"), renderIndex());
  console.log(`eslint: wrote rules/index.js with ${ruleFiles().length} rule(s)`);
}
