import type { SVGProps } from "react";

/*
 * The few icons the components need, drawn inline so the package has no
 * icon dependency. They are decorative and hidden from assistive technology:
 * the text next to them, or the aria-label of an icon-only button, carries the meaning.
 */

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

